# Builds the embedded Simplified Chinese font (runtime/zh_font.h) for the settings menu:
#   python tools/zh_font.py <NotoSansSC[wght].ttf> [--all]
# Without --all only the characters the menu's strings use are kept (with Latin and punctuation);
# with --all, GB2312's 3755 most common ideographs are added too (any Chinese text shows).
import json
import os
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "runtime", "zh_font.h")


def charset(with_gb2312):
    cps = set()
    for a, b in ((0x20, 0x7F), (0xA0, 0x100), (0x2000, 0x2070), (0x3000, 0x3040), (0xFF00, 0xFFF0)):
        cps.update(range(a, b))
    for s in json.load(open(os.path.join(HERE, "zh_strings.json"), encoding="utf-8")).values():
        cps.update(ord(c) for c in s)
    if with_gb2312:
        for hi in range(0xB0, 0xD8):
            for lo in range(0xA1, 0xFF):
                try:
                    cps.add(ord(bytes((hi, lo)).decode("gb2312")))
                except UnicodeDecodeError:
                    pass
    return cps


def main():
    if len(sys.argv) < 2:
        raise SystemExit("usage: zh_font.py <font.ttf> [--all]")
    src = sys.argv[1]
    f = TTFont(src)
    if "fvar" in f:
        instantiateVariableFont(f, {"wght": 400}, inplace=True)
    cps = charset("--all" in sys.argv)
    opts = subset.Options()
    opts.layout_features = ["kern", "liga", "locl", "ccmp"]
    opts.name_IDs = ["*"]
    opts.name_languages = ["*"]
    opts.notdef_outline = True
    opts.hinting = False
    opts.legacy_kern = False
    opts.drop_tables += ["DSIG", "vhea", "vmtx", "VORG"]
    s = subset.Subsetter(options=opts)
    s.populate(unicodes=cps)
    s.subset(f)
    tmp = os.path.join(HERE, "_zh_font.ttf")
    f.save(tmp)
    data = open(tmp, "rb").read()
    os.remove(tmp)
    cmap = TTFont(tmp, lazy=True) if False else None
    del cmap

    with open(OUT, "w", encoding="utf-8", newline="\n") as o:
        o.write("// Simplified Chinese font for the settings menu (Noto Sans SC, SIL Open Font License 1.1:\n")
        o.write("// tools/NotoSansSC-OFL.txt), instanced at Regular and subset to the glyphs the menu needs.\n")
        o.write("// Generated by tools/zh_font.py; do not edit.\n#pragma once\n\n")
        o.write("static const unsigned char zh_font_ttf[] = {\n")
        for i in range(0, len(data), 24):
            o.write(",".join("0x%02x" % b for b in data[i:i + 24]) + ",\n")
        o.write("};\n")
        o.write("static const int zh_font_ttf_size = %d;\n" % len(data))
    print("wrote %s: %d bytes" % (OUT, len(data)))


if __name__ == "__main__":
    main()