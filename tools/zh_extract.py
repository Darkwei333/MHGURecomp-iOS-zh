# Extracts the English strings of runtime/settings_locale.h as JSON, and (given
# tools/zh_strings.json, an object keyed by index) writes runtime/settings_locale_zh.h.
#   python tools/zh_extract.py dump
#   python tools/zh_extract.py gen
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "runtime", "settings_locale.h")
OUT = os.path.join(ROOT, "runtime", "settings_locale_zh.h")
ZH = os.path.join(HERE, "zh_strings.json")

ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "\\": "\\", '"': '"', "'": "'", "0": "\0"}


def parse_c_strings(block):
    """Yields the value of each C string literal / concatenation group, in order."""
    i, n = 0, len(block)
    while i < n:
        if block[i] != '"':
            i += 1
            continue
        parts = []
        while i < n and block[i] == '"':
            i += 1
            buf = []
            while i < n and block[i] != '"':
                if block[i] == "\\":
                    i += 1
                    c = block[i]
                    if c == "x":
                        m = re.match(r"[0-9a-fA-F]+", block[i + 1:])
                        buf.append(chr(int(m.group(0), 16)))
                        i += 1 + len(m.group(0))
                        continue
                    buf.append(ESCAPES.get(c, c))
                    i += 1
                else:
                    buf.append(block[i])
                    i += 1
            i += 1  # closing quote
            parts.append("".join(buf))
            while i < n and block[i] in " \t\r\n":
                i += 1
        yield "".join(parts)


def load_pairs():
    src = open(SRC, encoding="utf-8").read()
    body = src[src.index("messages[] = {"):src.index("};", src.index("messages[] = {"))]
    # One entry is {"en", "es"}: two literals (each possibly split over lines).
    vals = list(parse_c_strings(body))
    if len(vals) % 2:
        raise SystemExit("odd number of strings: %d" % len(vals))
    pairs = [(vals[i], vals[i + 1]) for i in range(0, len(vals), 2)]
    return [en for en, _ in pairs], [es for _, es in pairs]


def c_quote(s):
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return '"%s"' % out


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("dump", "gen"):
        raise SystemExit("usage: zh_extract.py dump|gen")
    en, es = load_pairs()
    if sys.argv[1] == "dump":
        json.dump(en, open(os.path.join(HERE, "zh_en.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)
        print("%d strings" % len(en))
        return
    zh = json.load(open(ZH, encoding="utf-8"))
    missing = [i for i in range(len(en)) if str(i) not in zh]
    extra = [k for k in zh if not (0 <= int(k) < len(en))]
    if missing or extra:
        raise SystemExit("missing %s extra %s" % (missing[:20], extra[:20]))
    for i, s in enumerate(en):
        fmt = re.findall(r"%[-+ #0-9.]*[a-zA-Z]", s)
        got = re.findall(r"%[-+ #0-9.]*[a-zA-Z]", zh[str(i)])
        if fmt != got:
            raise SystemExit("%d: format specifiers differ: %s vs %s (%r)" % (i, fmt, got, s))

    unused = [(i, en[i], es[i]) for i in range(len(en)) if str(i) not in zh]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Host UI only (generated by tools/zh_extract.py from tools/zh_strings.json): the settings menu's\n")
        f.write("// Simplified Chinese. INI keys and game content remain language-independent.\n")
        f.write("#pragma once\n#include <string.h>\n\n")
        f.write("static inline const char *settings_text_zh(const char *english) {\n")
        f.write("    static const struct { const char *en, *zh; } messages[] = {\n")
        for i, s in enumerate(en):
            f.write("        {%s,\n         %s},\n" % (c_quote(s), c_quote(zh[str(i)])))
        f.write("    };\n")
        f.write("    for (unsigned i = 0; i < sizeof messages / sizeof *messages; ++i)\n")
        f.write("        if (!strcmp(english, messages[i].en)) return messages[i].zh;\n")
        f.write("    return english;\n}\n")
    print("wrote %s (%d strings, %d untranslated)" % (OUT, len(en), len(unused)))
    for i, s, e in unused[:10]:
        print("  %d %s" % (i, s))


if __name__ == "__main__":
    main()